"""Return type per built-in filter. ``_T`` binds to the value's element type."""

_ELEMENTWISE = 'Iterable[_T]'
_HEADER = """\
\"""Generated by types-for-jinja. Signatures for Jinja's built-in filters and tests.\"""

from collections.abc import Iterable, Iterator
from typing import Any as _TJAny
from typing import TypeVar

_T = TypeVar('_T')


def _tj_test(value: _TJAny, /, *args: _TJAny, **kwargs: _TJAny) -> bool: ...
"""


def stub_name(filter_name: str) -> str:
    """Return the generated function name for ``filter_name``."""
    return f'_tj_f_{filter_name}'


def module_source() -> str:
    """Render the importable module holding every filter signature."""
    lines = [_HEADER]
    lines.extend(
        f'def {stub_name(name)}(value: {_value_type(returns)}, /, *args: _TJAny, **kwargs: _TJAny) -> {returns}: ...'
        for name, returns in sorted(RETURNS.items())
    )
    return '\n\n'.join(lines) + '\n'


def _value_type(returns: str) -> str:
    """A generic return has to bind ``_T``, which only the value argument can do."""
    return _ELEMENTWISE if '_T]' in returns or returns == '_T' else '_TJAny'
