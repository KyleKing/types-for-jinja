"""Type signatures for Jinja's built-in filters and tests.

The stub module below is written next to the generated code and imported by it, so a
filtered expression carries a real type instead of collapsing to ``Any``:
``{{ items | length }}`` is an ``int`` and ``{% for x in items | sort %}`` still knows
what ``x`` is.

Only the return type is pinned. Every filter takes its value as ``Any`` (except where a
generic preserves the element type) and swallows the remaining arguments, because a
filter catalog that guesses at argument types reports errors on correct templates, and a
checker that cries wolf gets uninstalled. Filters absent from ``RETURNS`` keep the old
``Any`` behaviour rather than a signature nobody verified.
"""

from __future__ import annotations

MODULE_NAME = '_tj_filters'
TEST_STUB = '_tj_test'

